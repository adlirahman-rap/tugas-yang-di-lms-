# 06_operator.py

a = 10
b = 3

# 1. Operator Aritmatika
print("--- Aritmatika ---")
print("Penjumlahan (a + b) :", a + b)
print("Pengurangan (a - b) :", a - b)
print("Perkalian (a * b)   :", a * b)
print("Pembagian (a / b)   :", a / b)
print("Sisa Bagi (a % b)   :", a % b)
print("Pangkat (a ** b)    :", a ** b)

# 2. Operator Perbandingan
print("\n--- Perbandingan ---")
print("Apakah a > b?", a > b)
print("Apakah a == b?", a == b)

# 3. Operator Logika
print("\n--- Logika ---")
x = True
y = False
print("True and False:", x and y)
print("True or False:", x or y)
print("not True:", not x)
